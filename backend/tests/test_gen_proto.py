"""
The code generated from proto/ (`tools/gen_proto.py`, `make proto`) is committed: `app/gen/`
(Python) and `../frontend/src/gen/` (TypeScript). It must be what the generators make of the
.proto files today — editing a .proto without `make proto`, or a generated file by hand, fails
here — made by the pinned generators, and importable.

A side whose generator is not installed is skipped: `pip install -r requirements-dev.txt`
(Python), `npm ci --prefix ../frontend` (TypeScript).
"""
import importlib
import json
import re
from pathlib import Path

import pytest

from tools import gen_proto

BACKEND = Path(__file__).resolve().parent.parent
PYTHON, TYPESCRIPT = gen_proto.TARGETS["python"], gen_proto.TARGETS["typescript"]


def require(target: gen_proto.Target) -> None:
    if target.missing():
        pytest.skip(f"{target.name} generator not installed: {target.install_hint}")


# ----- fresh -----------------------------------------------------------------------------------------
@pytest.mark.parametrize("target", [PYTHON, TYPESCRIPT], ids=lambda t: t.name)
def test_the_committed_code_is_what_the_generators_make_of_the_protos(target):
    require(target)
    diff = gen_proto.stale(target)
    assert not diff, "".join(diff[:60]) + f"\n{target.out} is stale: run `make proto`"


# ----- complete --------------------------------------------------------------------------------------
def test_every_proto_is_generated_on_both_sides():
    assert gen_proto.protos() == ["sincero/simulation_input.proto", "sincero/simulation_result.proto",
                                  "sincero/simulations_service.proto", "google/rpc/error_details.proto"]
    for proto in gen_proto.protos():
        stem = proto.removesuffix(".proto")
        assert (PYTHON.out / f"{stem}_pb.py").is_file(), stem
        assert (TYPESCRIPT.out / f"{stem}_pb.ts").is_file(), stem
    assert (PYTHON.out / "sincero" / "simulations_service_connect.py").is_file()


def test_buf_validate_is_imported_from_protovalidate_not_generated():
    assert not (PYTHON.out / "buf").exists() and not (TYPESCRIPT.out / "buf").exists()
    py = (PYTHON.out / "sincero" / "simulation_input_pb.py").read_text(encoding="utf-8")
    ts = (TYPESCRIPT.out / "sincero" / "simulation_input_pb.ts").read_text(encoding="utf-8")
    assert "from protovalidate._gen.buf.validate import validate_pb" in py
    assert 'from "@bufbuild/protovalidate/gen/buf/validate/validate_pb.js"' in ts


def test_every_python_module_imports():
    pytest.importorskip("connectrpc")
    for path in sorted(PYTHON.out.rglob("*.py")):
        module = ".".join(path.relative_to(BACKEND).with_suffix("").parts).removesuffix(".__init__")
        importlib.import_module(module)


# ----- by the pinned generators -----------------------------------------------------------------------
def pinned_pip(package: str) -> str:
    text = (BACKEND / "requirements-dev.txt").read_text(encoding="utf-8")
    match = re.search(rf"^{re.escape(package)}==(\S+)", text, re.M)
    assert match, f"{package} must be pinned with == in requirements-dev.txt (its version is in every generated file)"
    return match.group(1)


def locked_npm(package: str) -> str:
    lock = json.loads((gen_proto.FRONTEND / "package-lock.json").read_text(encoding="utf-8"))
    return lock["packages"][f"node_modules/{package}"]["version"]


@pytest.mark.parametrize("path, generator, version", [
    ("sincero/simulation_input_pb.py", "protoc-gen-py", lambda: pinned_pip("protoc-gen-py")),
    ("sincero/simulations_service_connect.py", "protoc-gen-connectrpc-py", lambda: pinned_pip("protoc-gen-connectrpc")),
])
def test_python_is_made_by_the_pinned_plugins(path, generator, version):
    header = (PYTHON.out / path).read_text(encoding="utf-8")
    assert f"# Generated by {generator} v{version()} " in header


def test_typescript_is_made_by_the_locked_plugin():
    for proto in gen_proto.protos():
        ts = (TYPESCRIPT.out / f"{proto.removesuffix('.proto')}_pb.ts").read_text(encoding="utf-8")
        assert f"// @generated by protoc-gen-es v{locked_npm('@bufbuild/protoc-gen-es')} " in ts, proto
